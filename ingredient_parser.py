
import re

# A small ingredient vocabulary for our dataset.
# We can extend it later.
INGREDIENT_ALIASES = {
    "творог": ["творог"],
    "яйцо": ["яйца", "яйцо", "яиц", "яйцами"],
    "мука": ["мука", "муки", "муку"],
    "кабачок": ["кабачок", "кабачки", "кабачков", "цукини"],
    "сыр": ["сыр", "сыра", "сыром", "чеддер", "моцарелла"],
    "молоко": ["молоко", "молока"],
    "сметана": ["сметана", "сметаны", "сметану"],
    "масло": ["масло", "масла"],
    "сахар": ["сахар", "сахара"],
    "картофель": ["картофель", "картошка", "картофеля"],
    "курица": ["курица", "куриная", "куриные", "курицу"],
    "говядина": ["говядина", "говядины"],
    "чечевица": ["чечевица", "чечевицу", "чечевицы"],
    "шпинат": ["шпинат", "шпината"],
    "яблоко": ["яблоки", "яблоко", "яблок", "яблоками"],
    "банан": ["бананы", "банан", "бананов"],
    "нут": ["нут", "нута", "нутом"],
}

def extract_ingredients(text):
    text = text.lower().replace("ё", "е")
    found = set()

    for canonical, aliases in INGREDIENT_ALIASES.items():
        for alias in aliases:
            pattern = rf"(?<!\w){re.escape(alias)}(?!\w)"
            if re.search(pattern, text):
                found.add(canonical)
                break

    return found


if __name__ == "__main__":
    example = "У меня есть творог, яйца и мука"
    print(extract_ingredients(example))
